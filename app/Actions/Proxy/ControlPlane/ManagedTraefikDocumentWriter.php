            '  if [ -L "$artifact_candidate" ] || [ ! -f "$artifact_candidate" ]; then continue; fi',
            '  read_artifact "$artifact_candidate" || continue',
            '  if [ "$journal_present" = true ]; then',
            '    if [ "$artifact_line_3" != "$journal_operation" ] || [ "$artifact_line_4" != "$journal_revision" ] || [ "$artifact_line_6" != "$journal_successor_sha" ]; then continue; fi',
            '  fi',
            '  if { [ "$journal_present" = true ] && { test "$live_document_sha" = "$expected_document_sha" || test "$live_document_sha" = "$artifact_line_6"; } && { cmp -s "$sidecar_path" "$expected_sidecar_file" || cmp -s "$sidecar_path" "$candidate_sidecar_file"; }; } || { test "$live_document_sha" = "$artifact_line_6" && { cmp -s "$sidecar_path" "$expected_sidecar_file" || cmp -s "$sidecar_path" "$candidate_sidecar_file"; }; } || { test "$live_document_sha" = "$expected_document_sha" && cmp -s "$sidecar_path" "$candidate_sidecar_file"; }; then',
            '    cp "$candidate_predecessor_file" "$predecessor_document_file" || fail',
            '    cp "$candidate_sidecar_file" "$successor_sidecar_file" || fail',
            '    selected_artifact=true',
            '    break',
            '  fi',
            'done',
            'test "$selected_artifact" = true || fail',
            'if ! document_matches "$expected_document_sha"; then atomic_replace "$document_path" "$predecessor_document_file" "$dynamic_directory"; fi',
            'if ! cmp -s "$sidecar_path" "$expected_sidecar_file"; then atomic_replace "$sidecar_path" "$expected_sidecar_file" "$state_directory"; fi',
            'document_matches "$expected_document_sha" || fail',
            'cmp -s "$sidecar_path" "$expected_sidecar_file" || fail',
            'if [ -e "$journal_path" ] || [ -L "$journal_path" ]; then atomic_remove "$journal_path" "$state_directory"; fi',
            'atomic_replace "$reconciled_marker_path" "$reconciled_marker_file" "$state_directory"',
            'durable_remote_remove "$journal_path" "$state_directory" || fail',
            'normalize_visible_state',
            'printf %s "$reconciled_output"',
        ]);
    }

    private function assertDocumentWriteAuthority(
        ManagedTraefikDocumentMutation $mutation,
        ManagedTraefikDocumentWriterAuthority $activeAuthority,
        bool $allowBootstrap,
    ): void {
        if ($allowBootstrap) {
            if ($activeAuthority->epoch !== 1 || ! $activeAuthority->matchesPredecessor($mutation)) {
                throw new InvalidArgumentException('Managed Traefik document writer authority bootstrap is limited to the exact initial epoch-one predecessor authority.');
            }

            return;
        }

        if (! $activeAuthority->matchesPredecessor($mutation)) {
            throw new InvalidArgumentException('The managed Traefik document write must require the exact active predecessor authority.');
        }
    }

    private function assertEnrollmentRollbackFinalizationAuthority(
        ManagedTraefikDocumentMutation $mutation,
        ManagedTraefikDocumentWriterAuthority $rolledBackAuthority,
    ): void {
        if ($mutation->expectedSidecar() !== null
            || $rolledBackAuthority->epoch !== 2
            || ! hash_equals($rolledBackAuthority->operationId, $mutation->operationId)
            || $rolledBackAuthority->dynamicRevision !== $mutation->revision
            || ! hash_equals(
                $rolledBackAuthority->dynamicSha256,
                $mutation->expectedSha256 ?? hash('sha256', ''),
            )) {
            throw new InvalidArgumentException('Enrollment rollback finalization requires the exact rolled-back authority and an unmanaged predecessor state.');
        }
    }

    private function assertAuthorityPromotion(
        ManagedTraefikDocumentWriterAuthority $expectedAuthority,
        ManagedTraefikDocumentWriterAuthority $nextAuthority,
    ): void {
        if ($nextAuthority->epoch !== $expectedAuthority->epoch + 1) {
            throw new InvalidArgumentException('A managed Traefik document writer authority promotion must advance exactly one epoch.');
        }
    }

    private function assertWriterAuthorityContext(string $stateDirectory, string $filename): void
    {
        if (! str_starts_with($stateDirectory, '/') || str_contains($stateDirectory, "\0")) {
            throw new InvalidArgumentException('The managed Traefik document writer authority state directory must be an absolute NUL-free path.');
        }

        if (basename($filename) !== $filename
            || preg_match('/\A[a-z0-9][a-z0-9.-]{0,127}\.ya?ml\z/D', $filename) !== 1) {
            throw new InvalidArgumentException('The managed Traefik document writer authority filename is invalid.');
        }
    }

    private function assertRollbackAuthority(
        ManagedTraefikDocumentMutation $mutation,
        ManagedTraefikDocumentWriterAuthority $predecessorAuthority,
        ManagedTraefikDocumentWriterAuthority $rolledBackAuthority,
    ): void {
        if (! $predecessorAuthority->matchesPredecessor($mutation)) {
            throw new InvalidArgumentException('The managed Traefik document rollback must require the exact predecessor authority and cannot downgrade a successor authority.');
        }
        if ($rolledBackAuthority->epoch !== $predecessorAuthority->epoch + 1
            || ! hash_equals($rolledBackAuthority->operationId, $mutation->operationId)
            || ! $rolledBackAuthority->matchesPredecessorDocument($mutation)
            || ! $rolledBackAuthority->hasSameWriterIdentityAs($predecessorAuthority)) {
            throw new InvalidArgumentException('The managed Traefik document rollback authority must fence the exact generation attempt while preserving its predecessor writer.');
        }
    }
