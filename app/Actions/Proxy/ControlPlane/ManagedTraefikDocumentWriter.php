    public function reconcileRolledBackWriterAuthorityCommandFor(
        ManagedTraefikDocumentMutation $mutation,
        ManagedTraefikDocumentWriterAuthority $predecessorAuthority,
        ManagedTraefikDocumentWriterAuthority $rolledBackAuthority,
    ): string {
        $this->assertRollbackAuthority($mutation, $predecessorAuthority, $rolledBackAuthority);

        return $this->rolledBackAuthorityReconciliationCommandFor(
            mutation: $mutation,
            predecessorAuthority: $predecessorAuthority,
            rolledBackAuthority: $rolledBackAuthority,
        );
    }

    private function commandFor(
        ManagedTraefikDocumentMutation $mutation,
        bool $rollback,
        ?ManagedTraefikDocumentWriterAuthority $requiredAuthority = null,
        ?ManagedTraefikDocumentWriterAuthority $nextAuthority = null,
        bool $allowMissingArtifactNoop = false,
        bool $allowAuthorityBootstrap = false,
        bool $allowAuthorityAbsence = false,
    ): string {
        $expectedSidecar = $mutation->expectedSidecar();
        $authorityMode = $requiredAuthority === null
            ? 'none'
            : ($nextAuthority === null ? 'require' : 'rollback');
        $requiredAuthority = $requiredAuthority?->toJson();
        $nextAuthority = $nextAuthority?->toJson();

        return implode("\n", [
            'set -eu',
            'umask 077',
