    private const JOURNAL_MAGIC = 'coolify-managed-traefik-document-journal-v1';

    public function rollbackArtifactFor(
        ManagedTraefikDocumentMutation $mutation,
        ?string $predecessorBytes,
    ): string {
        if (($predecessorBytes === null) !== ($mutation->expectedSha256 === null)
            || ($predecessorBytes !== null
                && ! hash_equals($mutation->expectedSha256 ?? '', hash('sha256', $predecessorBytes)))) {
            throw new InvalidArgumentException('The managed Traefik rollback artifact predecessor does not match its mutation.');
        }

        return implode("\n", [
            self::ARTIFACT_MAGIC,
            $mutation->filename,
            $mutation->operationId,
            (string) $mutation->revision,
            $mutation->expectedSha256 ?? 'absent',
            $mutation->replacementSha256(),
            $mutation->expectedSidecar() === null ? 'absent' : base64_encode($mutation->expectedSidecar()),
            $predecessorBytes === null ? 'absent' : base64_encode($predecessorBytes),
            '',
        ]);
    }

    public function writeCommandFor(ManagedTraefikDocumentMutation $mutation): string
    {
        return $this->commandFor($mutation, false);
    }

    public function rollbackCommandFor(
        ManagedTraefikDocumentMutation $mutation,
        bool $allowMissingArtifactNoop = false,
    ): string {
        return $this->commandFor(
            mutation: $mutation,
            rollback: true,
            allowMissingArtifactNoop: $allowMissingArtifactNoop,
        );
    }

    public function writeCommandForRequiringAuthority(
        ManagedTraefikDocumentMutation $mutation,
        ManagedTraefikDocumentWriterAuthority $activeAuthority,
        bool $allowBootstrap,
    ): string {
        $this->assertDocumentWriteAuthority($mutation, $activeAuthority, $allowBootstrap);

        return $this->commandFor(
            mutation: $mutation,
            rollback: false,
            requiredAuthority: $activeAuthority,
            allowAuthorityBootstrap: $allowBootstrap,
        );
    }

    public function promoteWriterAuthorityCommandFor(
        string $stateDirectory,
        string $filename,
        ManagedTraefikDocumentWriterAuthority $expectedAuthority,
        ManagedTraefikDocumentWriterAuthority $nextAuthority,
    ): string {
        $this->assertWriterAuthorityContext($stateDirectory, $filename);
        $this->assertAuthorityPromotion($expectedAuthority, $nextAuthority);

        return $this->authorityPromotionCommandFor(
            stateDirectory: $stateDirectory,
            filename: $filename,
            expectedAuthority: $expectedAuthority,
            nextAuthority: $nextAuthority,
        );
    }

    public function rollbackCommandForRequiringPredecessorAuthority(
        ManagedTraefikDocumentMutation $mutation,
        ManagedTraefikDocumentWriterAuthority $predecessorAuthority,
        ManagedTraefikDocumentWriterAuthority $rolledBackAuthority,
        bool $allowInitialOrPreWriteReconciliation = false,
        bool $allowMissingArtifactNoop = false,
    ): string {
        $this->assertRollbackAuthority($mutation, $predecessorAuthority, $rolledBackAuthority);

        return $this->commandFor(
            mutation: $mutation,
            rollback: true,
            requiredAuthority: $predecessorAuthority,
            nextAuthority: $rolledBackAuthority,
            allowMissingArtifactNoop: $allowMissingArtifactNoop,
            allowAuthorityAbsence: $allowInitialOrPreWriteReconciliation,
        );
    }

    public function rollbackEnrollmentCommandFor(
        ManagedTraefikDocumentMutation $mutation,
        ManagedTraefikDocumentWriterAuthority $replacementAuthority,
        ManagedTraefikDocumentWriterAuthority $rolledBackAuthority,
    ): string {
        if (! $replacementAuthority->matchesReplacement($mutation)
            || $rolledBackAuthority->epoch !== $replacementAuthority->epoch + 1
            || ! hash_equals($rolledBackAuthority->operationId, $mutation->operationId)
            || $rolledBackAuthority->dynamicRevision !== $mutation->revision
            || ! hash_equals(
                $rolledBackAuthority->dynamicSha256,
                $mutation->expectedSha256 ?? hash('sha256', ''),
            )
            || ! $rolledBackAuthority->hasSameWriterIdentityAs($replacementAuthority)) {
            throw new InvalidArgumentException('The enrollment rollback authority must fence the exact replacement and predecessor document.');
        }

        return $this->commandFor(
            mutation: $mutation,
            rollback: true,
            requiredAuthority: $replacementAuthority,
            nextAuthority: $rolledBackAuthority,
            allowMissingArtifactNoop: true,
            allowAuthorityAbsence: true,
        );
    }

